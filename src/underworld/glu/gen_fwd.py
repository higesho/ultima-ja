"""opengl32.dll（代わり）の、本物へそのままつなぐ部分を 32 ビット用と 64 ビット用に作る。
  python gen_fwd.py <出力フォルダ> <自分で書く関数（名前:x86 の引数のバイト数,...）>
作るもの（出力フォルダに）:
  fwd_names.h  … 本物の関数の名前の表と番号（IX_名前）。両方で同じ
  fwd32.h      … 32 ビット: 自分で書かない関数を本物へ飛ばす naked 関数と、書き出す名前（#pragma）
  fwd64.asm    … 64 ビット: 同じことを ml64 で
  fwd64.def    … 64 ビット: 書き出す名前
自分で書く関数は hk_名前（WINAPI）で C に書く。"""
import os
import sys
import pefile

SYS32 = r'C:\Windows\SysWOW64\opengl32.dll'
SYS64 = r'C:\Windows\System32\opengl32.dll'


def names_of(path):
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    return [e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name]


def main():
    out = sys.argv[1]
    hooks = {}
    for t in sys.argv[2].split(','):
        n, b = t.split(':')
        hooks[n] = int(b)
    n32, n64 = names_of(SYS32), names_of(SYS64)
    # 32 と 64 で名前の並びが違っても困らないように、両方の和を名前順に
    names = sorted(set(n32) | set(n64))
    for h in hooks:
        assert h in names, h
    h = ['/* gen_fwd.py が作る。手で直さない */', f'#define NREAL {len(names)}', 'static const char *real_names[NREAL] = {']
    h += [f'    "{n}",' for n in names] + ['};']
    h += [f'#define IX_{n} {i}' for i, n in enumerate(names)]
    open(os.path.join(out, 'fwd_names.h'), 'w', encoding='utf-8').write('\n'.join(h) + '\n')
    s = ['/* gen_fwd.py が作る。32 ビット用 */']
    for i, n in enumerate(names):
        if n not in n32:
            continue
        if n in hooks:
            s.append(f'#pragma comment(linker, "/EXPORT:{n}=_hk_{n}@{hooks[n]}")')
        else:
            s.append(f'__declspec(naked) void st_{n}(void) {{ __asm jmp dword ptr [g_real + {4 * i}] }}')
            s.append(f'#pragma comment(linker, "/EXPORT:{n}=_st_{n}")')
    open(os.path.join(out, 'fwd32.h'), 'w', encoding='utf-8').write('\n'.join(s) + '\n')
    a = ['; generated by gen_fwd.py (64-bit)', 'EXTERN g_real:QWORD', '.code']
    for i, n in enumerate(names):
        if n in hooks or n not in n64:
            continue
        a += [f'st_{n} PROC', f'    jmp QWORD PTR [g_real + {8 * i}]', f'st_{n} ENDP']
    a += ['END']
    open(os.path.join(out, 'fwd64.asm'), 'w', encoding='ascii').write('\n'.join(a) + '\n')
    d = ['LIBRARY opengl32', 'EXPORTS']
    for n in names:
        if n not in n64:
            continue
        d.append(f'    {n}=hk_{n}' if n in hooks else f'    {n}=st_{n}')
    open(os.path.join(out, 'fwd64.def'), 'w', encoding='ascii').write('\n'.join(d) + '\n')
    print(len(names), 'functions,', len(hooks), 'hooked')


if __name__ == '__main__':
    main()
