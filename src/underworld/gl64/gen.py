"""64 ビットの opengl32.dll（代わり）の、本物へそのままつなぐ部分を作る（dosbox-staging 用）
  exports.h   … 本物の関数の名前の表と番号
  stubs.asm   … 自分で書かない関数を、本物へそのまま飛ばす（ml64）
  exports.def … 書き出す名前
python gen.py"""
import os
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
SYS_GL = r'C:\Windows\System32\opengl32.dll'
# 自分で中身を書く関数（hk_ の名前で gl_proxy.c に書く）
HOOKS = ['glTexImage2D', 'glTexSubImage2D', 'wglGetProcAddress', 'glViewport', 'glDrawArrays']


def main():
    pe = pefile.PE(SYS_GL, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    names = [e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name]
    for h in HOOKS:
        assert h in names, h
    h = ['/* gen.py が作る。手で直さない */', f'#define NREAL {len(names)}', 'static const char *real_names[NREAL] = {']
    h += [f'    "{n}",' for n in names] + ['};']
    h += [f'#define IX_{n} {i}' for i, n in enumerate(names)]
    open(os.path.join(HERE, 'exports.h'), 'w', encoding='utf-8').write('\n'.join(h) + '\n')
    a = ['; generated by gen.py', 'EXTERN g_real:QWORD', '.code']
    for i, n in enumerate(names):
        if n in HOOKS: continue
        a += [f'st_{n} PROC', f'    jmp QWORD PTR [g_real + {8 * i}]', f'st_{n} ENDP']
    a += ['END']
    open(os.path.join(HERE, 'stubs.asm'), 'w', encoding='ascii').write('\n'.join(a) + '\n')
    d = ['LIBRARY opengl32', 'EXPORTS']
    for n in names:
        d.append(f'    {n}=hk_{n}' if n in HOOKS else f'    {n}=st_{n}')
    open(os.path.join(HERE, 'exports.def'), 'w', encoding='ascii').write('\n'.join(d) + '\n')
    print(len(names), 'functions,', len(HOOKS), 'hooked')


if __name__ == '__main__':
    main()
